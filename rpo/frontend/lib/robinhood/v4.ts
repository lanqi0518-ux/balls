export function assertKnownStock(ticker: string): keyof typeof V4_POOLS {
  const key = ticker.toUpperCase() as keyof typeof V4_POOLS;
  if (!(key in V4_POOLS)) {
    throw new Error(`No V4 pool configured for ${ticker}`);
  }
  return key;
}

